# =====================================================================
# КОЭФФИЦИЕНТЫ НА РАНГ КАРТЫ (21)
# =====================================================================
# Ранг карты = значение (Шесть, Семь, ..., Туз).
# Прогноз в 21 — всегда на игрока.
# Коэффициенты статичные.

PLAYER_COEFS = {
    "6": 3.325,
    "7": 3.28,
    "8": 3.26,
    "9": 3.2,
    "10": 3.195,
    "J": 3.56,
    "Q": 3.53,
    "K": 3.464,
    "A": 3.16,
}


# =====================================================================
# ПОЛУЧЕНИЕ КОЭФФИЦИЕНТА
# =====================================================================

def get_player_cf(rank: str) -> float:
    """Коэффициент на ранг у игрока (21)."""
    if rank is None:
        return 3.2
    rank = str(rank).strip().upper()
    return PLAYER_COEFS.get(rank, 3.2)


# Совместимость со старым кодом (если где-то вызывается из bot.py)
def get_dealer_cf(rank: str) -> float:
    """В 21 прогноз только на игрока — возвращаем коэффициент игрока."""
    return get_player_cf(rank)