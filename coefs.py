# =====================================================================
# СТАТИЧНЫЕ КОЭФФИЦИЕНТЫ НА КАРТУ ДИЛЕРА
# =====================================================================
# Прогноз всегда ищет карту У ДИЛЕРА → берём DEALER_COEFS.
# Карты только: J, Q, K, A (валеты, дамы, короли, тузы).

DEALER_COEFS = {
    "J♠": 11.9, "Q♠": 11.7, "K♠": 12.0, "A♠": 11.6,
    "J♣": 11.9, "Q♣": 11.8, "K♣": 12.0, "A♣": 11.6,
    "J♦": 11.9, "Q♦": 11.8, "K♦": 11.9, "A♦": 11.5,
    "J♥": 12.0, "Q♥": 11.9, "K♥": 11.7, "A♥": 11.5,
}

PLAYER_COEFS = {
    "J♠": 10.4, "Q♠": 10.3, "K♠": 10.2, "A♠": 10.0,
    "J♣": 10.2, "Q♣": 10.1, "K♣": 10.2, "A♣": 10.1,
    "J♦": 10.4, "Q♦": 10.1, "K♦": 10.4, "A♦": 10.1,
    "J♥": 10.3, "Q♥": 10.3, "K♥": 10.3, "A♥": 9.91,
}


def _norm(card: str) -> str:
    """Убирает ♣️ → ♣ (variation selector)."""
    return str(card).replace("\ufe0f", "")


def get_dealer_cf(card: str) -> float:
    """Коэффициент на карту дилера."""
    return DEALER_COEFS.get(_norm(card), 11.8)


def get_player_cf(card: str) -> float:
    """Коэффициент на карту игрока (на будущее)."""
    return PLAYER_COEFS.get(_norm(card), 10.2)
